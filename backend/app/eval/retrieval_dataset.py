"""
Golden dataset for retrieval quality — labeled (question -> relevant
glossary doc_id(s)) pairs, hand-written against the real corpus in
app/knowledge/glossary.py so ground truth is something a human actually
decided, not inferred from the retriever's own output.

This is the dataset the NeMo Evaluator suite (nemo_evaluator_suite.py)
runs its "assistant-retrieval" benchmark against — the retrieval-quality
eval coverage this app's Assistant chat never had before: every other
Golden Dataset case in golden_dataset.py exercises the main event
pipeline, never NeMo Retriever itself.

Most questions have exactly one relevant doc; a few legitimately overlap
two (e.g. a question about evacuation routing touches both the
evacuation_plan doc and the transtar doc that feeds its origin point) —
those list both, and a retrieval that surfaces either is a partial, not a
zero, credit under precision/recall.
"""
